CREATE TABLE ROL (
   ID_ROL        INTEGER        NOT NULL,
   NOMBRE        VARCHAR(50)    NOT NULL,
   CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL)
);

CREATE TABLE ESTADO (
   ID_ESTADO     INTEGER        NOT NULL,
   NOMBRE        VARCHAR(50)    NOT NULL,
   CONSTRAINT PK_ESTADO PRIMARY KEY (ID_ESTADO)
);

CREATE TABLE PROYECTO (
   ID_PROYECTO          INTEGER PRIMARY KEY AUTOINCREMENT,
   NOMBRE               VARCHAR(50)    NOT NULL,
   DESCRIPCION          VARCHAR(200),
   FECHA_INICIO         TEXT           NOT NULL,
   FECHA_FINALIZACION   TEXT           NOT NULL,
   ESTADO_GENERAL       VARCHAR(50)    NOT NULL,
   PORCENTAJE_DE_AVANCE REAL           NOT NULL
);

CREATE TABLE USUARIO (
   ID_USUARIO      INTEGER PRIMARY KEY AUTOINCREMENT,
   NOMBRE          VARCHAR(50)    NOT NULL,
   DESCRIPCION     VARCHAR(200),
   CORREO          VARCHAR(100)   NOT NULL,
   CONTRASENA      VARCHAR(100)   NOT NULL,
   ID_ROL          INTEGER        NOT NULL,
   CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
   CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL)
);

CREATE TABLE TAREA (
   ID_TAREA                INTEGER PRIMARY KEY AUTOINCREMENT,
   NOMBRE                  VARCHAR(50)    NOT NULL,
   DESCRIPCION             VARCHAR(200),
   FECHA_INICIO            TEXT           NOT NULL,
   FECHA_LIMITE            TEXT           NOT NULL,
   ID_ESTADO               INTEGER        NOT NULL,
   ID_PROYECTO             INTEGER        NOT NULL,
   ID_USUARIO_ASIGNA       INTEGER        NOT NULL,
   ID_USUARIO_DESARROLLA   INTEGER,
   CONSTRAINT FK_TAREA_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO(ID_ESTADO),
   CONSTRAINT FK_TAREA_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO) ON DELETE CASCADE,
   CONSTRAINT FK_TAREA_USUARIO_ASIGNA FOREIGN KEY (ID_USUARIO_ASIGNA) REFERENCES USUARIO(ID_USUARIO),
   CONSTRAINT FK_TAREA_USUARIO_DESARROLLA FOREIGN KEY (ID_USUARIO_DESARROLLA) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE REPORTES (
   ID_REPORTES             INTEGER PRIMARY KEY AUTOINCREMENT,
   NOMBRE                  VARCHAR(50)    NOT NULL,
   DESCRIPCION             VARCHAR(200),
   FECHA                   TEXT           NOT NULL,
   RESUMEN_DEL_PROGRESO    VARCHAR(500)   NOT NULL,
   TAREAS_ATRASADAS        INTEGER        NOT NULL,
   ID_PROYECTO             INTEGER        NOT NULL,
   CONSTRAINT FK_REPORTES_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO) ON DELETE CASCADE
);

