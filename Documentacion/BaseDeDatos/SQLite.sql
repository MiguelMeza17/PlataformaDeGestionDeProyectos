-- TRG_AVANCE_SIMPLE: recalcula porcentaje y estado del proyecto.
-- Oracle usaba un COMPOUND TRIGGER; SQLite necesita uno por evento.
CREATE TRIGGER TRG_AVANCE_SIMPLE_INSERT
AFTER INSERT ON TAREA
FOR EACH ROW
BEGIN
    UPDATE PROYECTO
    SET PORCENTAJE_DE_AVANCE = (
            SELECT ROUND(100.0 * SUM(CASE WHEN UPPER(E.NOMBRE) = 'FINISHED' THEN 1 ELSE 0 END) / COUNT(*), 2)
            FROM TAREA T JOIN ESTADO E ON E.ID_ESTADO = T.ID_ESTADO
            WHERE T.ID_PROYECTO = NEW.ID_PROYECTO)
    WHERE ID_PROYECTO = NEW.ID_PROYECTO;

    UPDATE PROYECTO
    SET ESTADO_GENERAL = CASE
                            WHEN PORCENTAJE_DE_AVANCE = 100 THEN 'Finished'
                            WHEN PORCENTAJE_DE_AVANCE = 0 THEN 'ToDevelop'
                            ELSE 'InDevelopment'
                         END
    WHERE ID_PROYECTO = NEW.ID_PROYECTO;
END;

CREATE TRIGGER TRG_AVANCE_SIMPLE_UPDATE
AFTER UPDATE ON TAREA
FOR EACH ROW
BEGIN
    UPDATE PROYECTO
    SET PORCENTAJE_DE_AVANCE = COALESCE((
            SELECT ROUND(100.0 * SUM(CASE WHEN UPPER(E.NOMBRE) = 'FINISHED' THEN 1 ELSE 0 END) / COUNT(*), 2)
            FROM TAREA T JOIN ESTADO E ON E.ID_ESTADO = T.ID_ESTADO
            WHERE T.ID_PROYECTO = PROYECTO.ID_PROYECTO), 0)
    WHERE ID_PROYECTO IN (NEW.ID_PROYECTO, OLD.ID_PROYECTO);

    UPDATE PROYECTO
    SET ESTADO_GENERAL = CASE
                            WHEN PORCENTAJE_DE_AVANCE = 100 THEN 'Finished'
                            WHEN PORCENTAJE_DE_AVANCE = 0 THEN 'ToDevelop'
                            ELSE 'InDevelopment'
                         END
    WHERE ID_PROYECTO IN (NEW.ID_PROYECTO, OLD.ID_PROYECTO);
END;

CREATE TRIGGER TRG_AVANCE_SIMPLE_DELETE
AFTER DELETE ON TAREA
FOR EACH ROW
BEGIN
    UPDATE PROYECTO
    SET PORCENTAJE_DE_AVANCE = COALESCE((
            SELECT ROUND(100.0 * SUM(CASE WHEN UPPER(E.NOMBRE) = 'FINISHED' THEN 1 ELSE 0 END) / COUNT(*), 2)
            FROM TAREA T JOIN ESTADO E ON E.ID_ESTADO = T.ID_ESTADO
            WHERE T.ID_PROYECTO = OLD.ID_PROYECTO), 0)
    WHERE ID_PROYECTO = OLD.ID_PROYECTO;

    UPDATE PROYECTO
    SET ESTADO_GENERAL = CASE
                            WHEN PORCENTAJE_DE_AVANCE = 100 THEN 'Finished'
                            WHEN PORCENTAJE_DE_AVANCE = 0 THEN 'ToDevelop'
                            ELSE 'InDevelopment'
                         END
    WHERE ID_PROYECTO = OLD.ID_PROYECTO;
END;

