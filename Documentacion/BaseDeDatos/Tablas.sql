DROP TABLE REPORTES CASCADE CONSTRAINTS;
DROP TABLE TAREA CASCADE CONSTRAINTS;
DROP TABLE USUARIO CASCADE CONSTRAINTS;
DROP TABLE ROL CASCADE CONSTRAINTS;
DROP TABLE PROYECTO CASCADE CONSTRAINTS;
DROP TABLE ESTADO CASCADE CONSTRAINTS;

CREATE TABLE ROL (
   ID_ROL        VARCHAR2(50)   NOT NULL,
   NOMBRE        VARCHAR2(50)   NOT NULL,
   CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL)
);

CREATE TABLE ESTADO (
   ID_ESTADO     VARCHAR2(50)   NOT NULL,
   NOMBRE        VARCHAR2(50)   NOT NULL,
   CONSTRAINT PK_ESTADO PRIMARY KEY (ID_ESTADO)
);

CREATE TABLE PROYECTO (
   ID_PROYECTO          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
   NOMBRE               VARCHAR2(50)   NOT NULL,
   DESCRIPCION          VARCHAR2(200),
   FECHA_INICIO         DATE           NOT NULL,
   FECHA_FINALIZACION   DATE           NOT NULL,
   ESTADO_GENERAL       VARCHAR2(50)   NOT NULL,
   PORCENTAJE_DE_AVANCE NUMBER(5,2)    NOT NULL,
   CONSTRAINT PK_PROYECTO PRIMARY KEY (ID_PROYECTO)
);

CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    NOMBRE          VARCHAR2(50)   NOT NULL,
    DESCRIPCION     VARCHAR2(200),
    CORREO          VARCHAR2(100)  NOT NULL,
    CONTRASENA      VARCHAR2(100)  NOT NULL,
    ID_ROL          VARCHAR2(50)   NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO)
);

CREATE TABLE TAREA (
   ID_TAREA                NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
   NOMBRE                  VARCHAR2(50)   NOT NULL,
   DESCRIPCION             VARCHAR2(200),
   FECHA_INICIO            DATE           NOT NULL,
   FECHA_LIMITE            DATE           NOT NULL,
   ID_ESTADO               VARCHAR2(50)   NOT NULL,
   ID_PROYECTO             NUMBER         NOT NULL,
   ID_USUARIO_ASIGNA       NUMBER         NOT NULL,
   ID_USUARIO_DESARROLLA   NUMBER,
   CONSTRAINT PK_TAREA PRIMARY KEY (ID_TAREA)
);

CREATE TABLE REPORTES (
   ID_REPORTES             NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
   NOMBRE                  VARCHAR2(50)   NOT NULL,
   DESCRIPCION             VARCHAR2(200),
   FECHA                   DATE           NOT NULL,
   RESUMEN_DEL_PROGRESO    VARCHAR2(500)  NOT NULL,
   TAREAS_ATRASADAS        NUMBER(10)     NOT NULL,
   ID_PROYECTO             NUMBER         NOT NULL,
   CONSTRAINT PK_REPORTES PRIMARY KEY (ID_REPORTES)
);

ALTER TABLE USUARIO ADD CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL);
ALTER TABLE TAREA ADD CONSTRAINT FK_TAREA_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO(ID_ESTADO);
ALTER TABLE TAREA ADD CONSTRAINT FK_TAREA_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO);
ALTER TABLE TAREA ADD CONSTRAINT FK_TAREA_USUARIO_ASIGNA FOREIGN KEY (ID_USUARIO_ASIGNA) REFERENCES USUARIO(ID_USUARIO);
ALTER TABLE TAREA ADD CONSTRAINT FK_TAREA_USUARIO_DESARROLLA FOREIGN KEY (ID_USUARIO_DESARROLLA) REFERENCES USUARIO(ID_USUARIO);
ALTER TABLE REPORTES ADD CONSTRAINT FK_REPORTES_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO);